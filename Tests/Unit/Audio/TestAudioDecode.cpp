// A path in the system temp dir, unique enough that two cases cannot collide.
std::string TempPath(const char* name) {
    std::filesystem::path p = std::filesystem::temp_directory_path();
    p /= (std::string("enjin_audio_test_") + name);
    return p.string();
}

bool WriteBytes(const std::string& path, const void* data, usize size) {
    std::ofstream f(path, std::ios::binary);
    if (!f.is_open()) return false;
    f.write(static_cast<const char*>(data), static_cast<std::streamsize>(size));
    return f.good();
}

// Integration tests clean up after themselves.
struct ScopedFile {
    std::string path;
    explicit ScopedFile(std::string p) : path(std::move(p)) {}
    ~ScopedFile() { std::remove(path.c_str()); }
};

