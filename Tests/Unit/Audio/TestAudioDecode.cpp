// Ogg Vorbis really decodes in this build, and an undecodable file really fails.
//
// Both halves used to be false. miniaudio compiles its Vorbis decoder only
// `#ifdef STB_VORBIS_INCLUDE_STB_VORBIS_H`, and MiniaudioImpl.cpp -- the single
// MINIAUDIO_IMPLEMENTATION translation unit -- never included stb_vorbis. So no
// build carried a Vorbis decoder, while the editor offered `.ogg` in every
// audio file filter, the thumbnailer accepted it, and BuildPipeline packed it
// into the shipped game.
//
// Nothing complained, because LoadClip verified a clip by calling
// ifstream::is_open() on it. That answers "is there a file here", which it then
// recorded as "clip loaded". So you picked an ogg, it showed as assigned, the
// build succeeded, and the sound was silent at play time -- and a .txt renamed
// to .wav behaved exactly the same way. A comment in AudioEngine.cpp said
// "miniaudio supports WAV, MP3, FLAC, and Vorbis natively", which is true of
// miniaudio and was not true of this build.
//
